"""Single owner of the persistent chDB instance in this process.

- An exclusive flock on <data_dir>/app.lock is taken BEFORE chDB is opened and
  held for the process lifetime, so a second backend (another terminal, a
  dev reload, a second worker) exits instead of running duplicate RMVs.
- chDB serialises foreground queries across sessions of one path (measured),
  so every call goes through one worker thread. RMV refreshes run in chDB's
  own background pool and are not blocked by this executor.
- The NC encryption key reaches chDB only through this process's environment
  (`key_hex from_env`); it is not written to the generated config file.
"""

from __future__ import annotations

import fcntl
import json
import logging
import os
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

from chdb import session as chs

from .keystore import KeyMaterial
from .settings import Settings

log = logging.getLogger(__name__)

KEY_ENV = "MLH_NC_KEY_HEX"


class AlreadyRunning(RuntimeError):
    pass


def acquire_lock(path: Path) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError as exc:
        os.close(fd)
        raise AlreadyRunning(f"another mini-loghouse backend holds {path}") from exc
    os.ftruncate(fd, 0)
    os.write(fd, str(os.getpid()).encode())
    return fd


def render_config(settings: Settings) -> str:
    ca = settings.tls_ca_file
    tls_client = (
        f"<caConfig>{ca}</caConfig><loadDefaultCAFile>false</loadDefaultCAFile>"
        if ca else "<loadDefaultCAFile>true</loadDefaultCAFile>"
    )
    return f"""<clickhouse>
    <!-- generated by mini-loghouse; contains no secrets -->
    <named_collections_storage>
        <type>local_encrypted</type>
        <algorithm>aes_128_ctr</algorithm>
        <key_hex from_env="{KEY_ENV}"/>
    </named_collections_storage>
    <openSSL><client>
        {tls_client}
        <verificationMode>strict</verificationMode>
        <invalidCertificateHandler><name>RejectCertificateHandler</name></invalidCertificateHandler>
    </client></openSSL>
</clickhouse>
"""


def write_private(path: Path, content: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(content)
    os.replace(tmp, path)


class ChdbOwner:
    def __init__(self, settings: Settings, key: KeyMaterial) -> None:
        self._settings = settings
        settings.data_dir.mkdir(parents=True, exist_ok=True)
        os.chmod(settings.data_dir, 0o700)
        self._lock_fd = acquire_lock(settings.lock_path)
        write_private(settings.chdb_config_path, render_config(settings))
        os.environ[KEY_ENV] = key.key_hex
        self._executor = ThreadPoolExecutor(max_workers=1, thread_name_prefix="chdb")
        self._session = self._executor.submit(self._open).result()

    def _open(self) -> chs.Session:
        conn = f"file:{self._settings.chdb_path}?config-file={self._settings.chdb_config_path}"
        return chs.Session(conn)

    def _rows(self, sql: str, params: dict | None) -> list[dict[str, Any]]:
        out = self._session.query(sql, "JSONEachRow", params=params).bytes().decode()
        return [json.loads(line) for line in out.splitlines() if line.strip()]

    def _execute(self, sql: str, params: dict | None) -> None:
        self._session.query(sql, "TSV", params=params)

    def rows(self, sql: str, params: dict | None = None) -> list[dict[str, Any]]:
        return self._executor.submit(self._rows, sql, params).result()

    def execute(self, sql: str, params: dict | None = None) -> None:
        self._executor.submit(self._execute, sql, params).result()

    def close(self) -> None:
        try:
            self._executor.submit(self._session.close).result()
        finally:
            self._executor.shutdown(wait=True)
            os.environ.pop(KEY_ENV, None)
            os.close(self._lock_fd)
